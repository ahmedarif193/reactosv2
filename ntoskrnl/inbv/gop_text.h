static __inline const UCHAR* GopText_GetRows5x7(UCHAR ch)
{
    if (ch >= 'a' && ch <= 'z') ch -= 32;
    for (ULONG i = 0; i < ARRAYSIZE(_Gop_BootGlyphs); ++i)
        if (_Gop_BootGlyphs[i].ch == ch) return _Gop_BootGlyphs[i].rows;
    static const UCHAR _unk[BOOTFONT_H] = {0x1F,0x11,0x15,0x15,0x11,0x1F,0x00};
    return _unk;
}

/* ===== API ===== */

static __inline VOID GopText_Init(
    GOP_TEXT_CTX* ctx,
    ULONG screen_w,
    ULONG screen_h,
    const GOP_TEXT_VTBL* vtbl,
    void* user)
{
    ctx->screen_w = screen_w;
    ctx->screen_h = screen_h;
    ctx->cursor_x = 0;
    ctx->cursor_y = 0;
    ctx->color    = 0xFFFFFF;
    ctx->opaque   = TRUE;
    ctx->vtbl     = vtbl;
    ctx->user     = user;
}

static __inline VOID GopText_SetColor(GOP_TEXT_CTX* ctx, ULONG rgb) { ctx->color = rgb; }
static __inline VOID GopText_SetOpaque(GOP_TEXT_CTX* ctx, BOOLEAN opaque) { ctx->opaque = opaque; }
static __inline VOID GopText_SetCursor(GOP_TEXT_CTX* ctx, ULONG x, ULONG y) { ctx->cursor_x = x; ctx->cursor_y = y; }

static __inline VOID _GopText_ScrollIfNeeded(GOP_TEXT_CTX* ctx)
{
    if (ctx->cursor_y + BOOTCHAR_HEIGHT <= ctx->screen_h) return;
    if (ctx->vtbl && ctx->vtbl->scroll_up) ctx->vtbl->scroll_up(BOOTCHAR_HEIGHT, ctx->user);
    if (ctx->screen_h >= BOOTCHAR_HEIGHT) ctx->cursor_y = ctx->screen_h - BOOTCHAR_HEIGHT;
}

static __inline VOID GopText_DrawGlyph5x7(GOP_TEXT_CTX* ctx, ULONG x, ULONG y, UCHAR ch)
{
    const UCHAR* rows = GopText_GetRows5x7(ch);
    ULONG xm = x + (BOOTCHAR_WIDTH  - BOOTFONT_W) / 2;
    ULONG ym = y + (BOOTCHAR_HEIGHT - BOOTFONT_H) / 2;

    for (ULONG r = 0; r < BOOTFONT_H; ++r)
    {
        UCHAR bits = rows[r];
        for (ULONG c = 0; c < BOOTFONT_W; ++c)
        {
            ULONG px = xm + c, py = ym + r;
            if (px >= ctx->screen_w || py >= ctx->screen_h) continue;
            if (bits & (0x10u >> c)) {
                if (ctx->vtbl && ctx->vtbl->put_pixel) ctx->vtbl->put_pixel(px, py, ctx->color, ctx->user);
            } else if (ctx->opaque) {
                if (ctx->vtbl && ctx->vtbl->put_pixel) ctx->vtbl->put_pixel(px, py, 0x000000, ctx->user);
            }
        }
    }
}

static __inline VOID GopText_PutChar(GOP_TEXT_CTX* ctx, UCHAR ch)
{
    if (ch == '\r') { ctx->cursor_x = 0; return; }
    if (ch == '\n') { ctx->cursor_x = 0; ctx->cursor_y += BOOTCHAR_HEIGHT; _GopText_ScrollIfNeeded(ctx); return; }

    GopText_DrawGlyph5x7(ctx, ctx->cursor_x, ctx->cursor_y, ch);
    ctx->cursor_x += BOOTCHAR_WIDTH;
    if (ctx->cursor_x + BOOTCHAR_WIDTH > ctx->screen_w) {
        ctx->cursor_x = 0;
        ctx->cursor_y += BOOTCHAR_HEIGHT;
        _GopText_ScrollIfNeeded(ctx);
    }
}

static __inline VOID GopText_Write(GOP_TEXT_CTX* ctx, const UCHAR* str)
{
    if (!str) return;
    while (*str) { GopText_PutChar(ctx, *str++); }
}

