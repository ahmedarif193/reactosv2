#ifndef ARRAYSIZE
  #define ARRAYSIZE(a) (sizeof(a)/sizeof((a)[0]))
#endif

/* ===== Cell + font sizes ===== */
#ifndef BOOTCHAR_WIDTH
  #define BOOTCHAR_WIDTH  8
#endif
#ifndef BOOTCHAR_HEIGHT
  #define BOOTCHAR_HEIGHT 13
#endif
#define BOOTFONT_W 5
#define BOOTFONT_H 7

/* ===== Interfaces ===== */
typedef struct _GOP_TEXT_CTX   GOP_TEXT_CTX;
typedef struct _GOP_TEXT_VTBL  GOP_TEXT_VTBL;

struct _GOP_TEXT_VTBL {
    void (*put_pixel)(ULONG x, ULONG y, ULONG rgb, void* user);
    void (*scroll_up)(ULONG pixels, void* user); /* scroll whole FB up, clear bottom area */
};

struct _GOP_TEXT_CTX {
    ULONG screen_w;
    ULONG screen_h;
    ULONG cursor_x;
    ULONG cursor_y;
    ULONG color;        /* 0x00RRGGBB */
    BOOLEAN opaque;     /* background fill for 0-bits */
    const GOP_TEXT_VTBL* vtbl;
    void* user;
};

